# -*- coding: utf-8 -*-
"""用 Pillow 生成 4 张测试幻灯片 PNG（1600x900，含大号页码与文字）。"""
import os

from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "slides")
os.makedirs(OUT, exist_ok=True)

W, H = 1600, 900
BG_COLORS = ["#1F2A44", "#2D3B2E", "#3A2A33", "#22333B"]
ACCENT = "#FB7299"

FONTS = [
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\arial.ttf",
    r"C:\Windows\Fonts\segoeuib.ttf",
    r"C:\Windows\Fonts\consola.ttf",
]


def load_font(size):
    for p in FONTS:
        if os.path.exists(p):
            try:
                return ImageFont.truetype(p, size)
            except Exception:
                continue
    return ImageFont.load_default()


for i in range(4):
    img = Image.new("RGB", (W, H), BG_COLORS[i])
    d = ImageDraw.Draw(img)
    # 顶部标题条
    d.rectangle([0, 0, W, 120], fill=ACCENT)
    title = load_font(54)
    body = load_font(40)
    d.text((60, 30), f"Test Slide {i+1}", fill="white", font=title)
    d.text((80, 300), "PPTX generated by BiliPptx builder", fill="white", font=body)
    d.text((80, 380), "zip(store) + OOXML, no dependencies", fill="#C9D1D9", font=body)
    # 大号页码
    d.text((W - 420, 560), f"P{i+1}", fill=ACCENT, font=load_font(220))
    # 柱状图装饰
    for j, h in enumerate((140, 240, 90, 180)):
        x = 80 + j * 120
        d.rounded_rectangle([x, 800 - h, x + 70, 800], radius=12, fill="#5B9BD5")
    img.save(os.path.join(OUT, f"slide{i+1}.png"))
    print(f"slide{i+1}.png OK")
print("done ->", OUT)
